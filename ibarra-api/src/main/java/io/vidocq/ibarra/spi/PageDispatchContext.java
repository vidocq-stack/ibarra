package io.vidocq.ibarra.spi;

/** Request-owned dispatch state used to terminate pages after an included forward. */
public interface PageDispatchContext {
    /**
     * Whether a forward from this page or an included descendant completed successfully.
     * Generated pages then stop their body and suppress pending writer flushes.
     * Implementations reset this state when their page context is initialized or released.
     */
    boolean isForwarded();
}
